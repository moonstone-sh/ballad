local cache = require("ballad.cache")
local fs = require("ballad.fs")
local process = require("ballad.process")
local action = require("ballad.native_action")
local partiture = require("ballad.partiture")
local glob = require("ballad.glob")
local node = { plugin = "fixture", method = "compile", options = {} }
local function key(asset) return cache.compute_key(node, { { assets = { asset } } }, "1") end
local function write(p, content) fs.mkdir(require("ballad.path").dirname(p)); fs.write_file(p, content) end
local function mtime(p)
  return process.capture("python3 -c " .. process.quote("import os; print(os.stat(" .. string.format("%q", p) .. ").st_mtime_ns)"))
end
assert(glob.matches("src/main.lua", "src/**/*.lua"))
assert(glob.matches("src/x/b/main.lua", "src/**/b/**/*.lua"))
assert(not glob.matches("src/a/main.lua", "src/*.lua"))
write("source.lua", "return 1")
assert(key({source_path="source.lua",content="return 1"})~=key({source_path="source.lua",content="return 2"}))
assert(key({content="same",virtual_path="a.lua"})~=key({content="same",virtual_path="b.lua"}))
assert(key({content="same",metadata={target="client"}})~=key({content="same",metadata={target="server"}}))
write("src/server.lua", "server v1"); write("public/app.js", "client v1")
local build=action.new({id="fixture.server",tool="sh",args={"-c","mkdir -p build; cat src/server.lua > build/server; printf x >> count"},inputs={"src/**/*.lua"},outputs={"build/server"}})
assert(not action.run(build).cache_hit); assert(action.run(build).cache_hit)
write("public/app.js", "client v2"); assert(action.run(build).cache_hit,"browser-only edit rebuilt server")
write("src/server.lua", "server v2"); assert(not action.run(build).cache_hit,"direct-child source edit missed")
write("build/server", "corrupted"); assert(not action.run(build).cache_hit,"corrupt output reused")
assert(fs.read_file("build/server")=="server v2")
write("src/nested/helper.lua", "helper"); assert(not action.run(build).cache_hit,"new input missed")
os.remove("src/nested/helper.lua"); assert(action.run(build).cache_hit)
write("tree/nested/file", "one"); cache.store("directory-test",nil,{"tree"})
local entry=cache.read("directory-test"); assert(cache.outputs_valid(entry))
os.remove("tree/nested/file"); assert(not cache.outputs_valid(entry),"missing output child accepted")
write("tree/nested/file", "one"); write("tree/extra", "unexpected")
assert(not cache.outputs_valid(entry),"unexpected output child accepted")
write("input/keep.lua", "return true"); write("input/nested/old.lua", "return false")
local function export()
 local pipeline=partiture.build(function(p)
  p.sink.directory(p.source.files({"**/*.lua"},{root="input"}),{out="output",incremental=true})
 end); pipeline:execute()
end
export(); local stamp=mtime("output/keep.lua"); export()
assert(stamp==mtime("output/keep.lua"),"unchanged sink rewrote its file")
os.remove("input/nested/old.lua"); write("input/new.lua", "return false"); export()
assert(not fs.read_file("output/nested/old.lua")); assert(fs.read_file("output/new.lua")=="return false")
assert(stamp==mtime("output/keep.lua"))
local sync=require("ballad.directory_sink")
assert(not pcall(sync.prepare,"output",{{virtual_path="../escape",content="bad"}},false))
assert(not pcall(sync.prepare,"output",{{virtual_path="..\\escape",content="bad"}},false))
assert(not pcall(sync.prepare,"output",{{virtual_path="a"},{virtual_path="a/b"}},false))
if not process.is_windows() then
 fs.mkdir("outside"); process.command_ok("ln -s ../outside output/link")
 assert(not pcall(sync.prepare,"output",{{virtual_path="link/escape"}},false)); assert(not fs.read_file("outside/escape"))
end
print("PASS: incremental cache, input membership, output integrity, stable sinks and safe pruning")
