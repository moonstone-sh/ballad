package.path = "src/?.lua;src/?/init.lua;" .. package.path
require("moonstone.variants").install()
local process = require("ballad.process")
local fs = require("ballad.fs")
local path = require("ballad.path")
assert(process.is_windows(), "Windows flavor not selected")
local root = assert(os.getenv("TEMP")):gsub("\\", "/") .. "/ballad native space"
fs.mkdir(root)
assert(fs.is_dir(root), "empty directory not recognized")
local realpath = require("ballad.realpath")
local physical = realpath.resolve(root)
assert(physical == realpath.resolve(root .. "/."), "physical directory resolution is unstable")
local outside = root .. " outside"
local junction = path.join(root,"junction")
fs.mkdir(outside)
assert(process.command_ok("mklink /J " .. process.quote(junction) .. " " .. process.quote(outside) .. " >NUL"))
assert(not path.contains(physical,realpath.resolve(junction)), "junction escape was treated as a child directory")
assert(process.command_ok("rmdir " .. process.quote(junction)))
fs.remove_tree(outside)
local probe = path.join(root, "probe.lua")
fs.write_file(probe, 'assert(arg[1] == "space value"); assert(os.getenv("BALLAD_NATIVE_TEST") == "value"); print("native task"); os.exit(7)')
assert(#fs.list_files(root) >= 1, "directory listing omitted probe.lua")
local result = process.capture_run({tool="lua",args={probe,"space value"},cwd=root,env={BALLAD_NATIVE_TEST="value"}})
assert(result.exit_code == 7, "native task exit code: " .. tostring(result.exit_code))
assert(result.stdout:find("native task",1,true), result.stdout)
fs.write_file(path.join(root,"old.txt"),"old")
fs.write_file(path.join(root,"new.txt"),"new")
assert(fs.replace_file(path.join(root,"new.txt"),path.join(root,"old.txt")))
assert(fs.read_file(path.join(root,"old.txt")) == "new")
fs.remove_tree(root)
print("PASS: native Windows task, capture, cwd, environment, replacement and cleanup")
